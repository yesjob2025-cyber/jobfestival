export function cardDetail(d: Drawn, i: number, topic: TopicId): CardDetail {
  return {
    scene: SCENES[d.card.id] ?? "",
    meaning: d.reversed ? d.card.rev : d.card.up,
    position: positionText(i, d),
    topic: TOPIC_TEXT[topic][d.card.suit],
    advice: d.card.advice,
    job: d.card.job,
  };
}

/** 결론 — 한 줄 판정 · 오늘 할 일 3가지 · 행운 정보 */
export function conclusionOf(drawn: Drawn[], topic: TopicId) {
  const t = TOPICS.find((x) => x.id === topic)!;
  const ups = drawn.filter((d) => !d.reversed).length;
  const verdict =
    ups === 3
      ? { emoji: "🌟", title: "순풍이 부는 흐름", text: `${t.lead}은 지금 하던 대로 자신 있게 밀고 나가면 좋은 결과가 기대되는 흐름이에요.` }
      : ups === 2
        ? { emoji: "👍", title: "상승하는 흐름", text: `${t.lead}은 좋은 쪽으로 올라가는 중이에요. 조언 카드 한 가지만 더 실천하면 합격권이에요.` }
        : ups === 1
          ? { emoji: "🌱", title: "다지는 흐름", text: `${t.lead}은 기초를 다지는 시기예요. 방향을 조금 다듬으면 반전이 일어나요.` }
          : { emoji: "🔄", title: "전환점의 흐름", text: `${t.lead}은 방법을 바꿔야 할 때라는 신호예요. 하나만 바꿔도 흐름이 단번에 뒤집혀요.` };
  return {
    verdict,
    actions: drawn.map((d, i) => ({ from: `${POSITIONS[i].name} · ${d.card.ko}`, text: d.card.advice })),
    luck: luckOf(drawn, topic),
  };
}
