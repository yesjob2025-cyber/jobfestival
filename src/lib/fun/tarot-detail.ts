/** 자리 × 방향 */
function positionText(i: number, d: Drawn): string {
  const k = d.card.keywords;
  const kw = `‘${k[0]}’`;
  if (i === 0)
    return d.reversed
      ? `지금 당신 안의 ${kw} 기운이 잠시 막혀 있어요. 힘이 없어서가 아니라 방향을 고르는 중이라는 뜻이니, 이 카드가 알려 주는 방법으로 풀어 보세요.`
      : `지금 당신은 ${kw} 기운 한가운데 서 있어요. ${k.slice(1).join(" · ")} — 이 장점이 지금 가장 잘 드러나는 때예요.`;
  if (i === 1)
    return d.reversed
      ? `기회는 분명히 다가오지만, ${kw} 쪽 준비가 조금 덜 되면 스쳐 지나갈 수 있어요. 미리 채워 두면 오히려 남보다 먼저 잡아요.`
      : `가까운 시일 안에 ${kw} · ‘${k[1] ?? k[0]}’${batchim(k[1] ?? k[0]) ? "과" : "와"} 닿아 있는 기회가 찾아와요. 연락 · 공고 · 사람을 통해 올 수 있으니 안테나를 세워 두세요.`;
  return d.reversed
    ? `이번 조언의 핵심은 ${kw}${batchim(k[0]) ? "을" : "를"} 넘치지도 모자라지도 않게 조절하는 거예요. 지나치면 줄이고, 부족하면 하나만 채우세요.`
    : `합격의 열쇠는 ${kw}${batchim(k[0]) ? "이에요" : "예요"}. 이 카드가 가진 장점을 그대로 행동으로 옮기면 결과가 따라와요.`;
}

