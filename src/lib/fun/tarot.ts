/** 78장을 섞고, 카드마다 약 30% 확률로 역방향 */
export function shuffledDeck(): Drawn[] {
  const deck = TAROT.map((card) => ({ card, reversed: Math.random() < 0.3 }));
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }
  return deck;
}

const LUCKY_ITEMS = ["네이비 넥타이", "손목시계", "하늘색 셔츠", "단정한 구두", "자신감 있는 미소", "검은 볼펜", "포트폴리오 파일", "깔끔한 헤어", "물 한 병", "따뜻한 커피"];
const LUCKY_COLORS = ["스카이 블루", "네이비", "옐로", "코랄 핑크", "화이트", "민트", "골드"];

/** 뽑은 카드로 정해지는 행운 정보 — 같은 카드면 같은 결과 */
export function luckOf(drawn: Drawn[], topic: TopicId) {
  const seed = drawn.reduce((a, d) => a * 31 + d.card.id.charCodeAt(0) * 7 + d.card.rank + (d.reversed ? 3 : 0), topic.length * 101);
  const ups = drawn.filter((d) => !d.reversed).length;
  return {
    score: 78 + ups * 5 + (seed % 7),
    item: LUCKY_ITEMS[seed % LUCKY_ITEMS.length],
    color: LUCKY_COLORS[(seed >> 3) % LUCKY_COLORS.length],
    job: drawn[1].card.job,
  };
}

/** 카드 세 장을 합쳐 읽는 종합 풀이 (AI 풀이를 못 쓸 때도 자세하게) */
export function summaryOf(drawn: Drawn[], topic: TopicId): string {
  const t = TOPICS.find((x) => x.id === topic)!;
  const majors = drawn.filter((d) => d.card.suit === "major").length;
  const revs = drawn.filter((d) => d.reversed).length;
  const suits = drawn.map((d) => d.card.suit).filter((s) => s !== "major");
  const top = (["wands", "cups", "swords", "pentacles"] as const)
    .map((s) => ({ s, n: suits.filter((x) => x === s).length }))
    .sort((a, b) => b.n - a.n)[0];

  const parts: string[] = [];
  parts.push(
    majors >= 2
      ? `${t.lead}에 메이저 카드가 ${majors}장이나 나왔어요. 지금은 인생의 방향이 크게 바뀌는 중요한 시기예요.`
      : `${t.lead}은 일상 속 작은 선택들이 쌓여 결과를 만드는 흐름이에요.`,
  );
  if (top && top.n >= 2) parts.push(`특히 ${SUIT_INFO[top.s].ko} 카드가 많아 ‘${SUIT_INFO[top.s].theme}’이(가) 이번 운세의 열쇠예요.`);
  parts.push(
    revs === 0
      ? "세 장 모두 정방향이라 흐름이 아주 순조로워요. 지금 하던 대로 자신 있게 밀고 나가세요!"
      : revs === 3
        ? "세 장 모두 역방향이에요. 잠시 숨 고르기가 필요하다는 신호이니, 방법을 하나 바꾸면 흐름이 단번에 뒤집혀요."
        : `역방향 카드가 ${revs}장 있어요. 막힌 곳이 어디인지 알려 주는 힌트이니, 조언 카드를 꼭 실천해 보세요.`,
  );
  parts.push(`${drawn[2].card.ko} 카드의 조언처럼 — ${drawn[2].card.advice}`);
  return parts.join(" ");
}
